export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en');
  const [country, setCountryState]   = useState<string>('');

  useEffect(() => {
    if (typeof window === 'undefined') return;
    const stored = window.localStorage.getItem('language') as Language | null;
    if (stored && ['en', 'fr', 'ar', 'zh'].includes(stored)) {
      applyLang(stored);
      setLanguageState(stored);
    }
    const storedCountry = window.localStorage.getItem('country');
    if (storedCountry) setCountryState(storedCountry);
  }, []);

  const applyLang = (lang: Language) => {
    document.documentElement.lang = lang;
    document.documentElement.dir  = lang === 'ar' ? 'rtl' : 'ltr';
  };

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    if (typeof window !== 'undefined') window.localStorage.setItem('language', lang);
    applyLang(lang);
  };

  const setCountry = (c: string) => {
    setCountryState(c);
    if (typeof window !== 'undefined') window.localStorage.setItem('country', c);
    // Auto-switch to Arabic for Arab countries
    if (ARAB_COUNTRIES.has(c)) {
      setLanguage('ar');
    }
  };

  const t = (key: string) => {
    const table = messages[language] || messages.en;
    return table[key] || messages.en[key] || key;
  };

  const formatCurrency = (amount: number, fromCurrencyCode?: string): string => {
    const cfg = getCurrencyCfg(country, language);
    let displayAmount = amount;
    if (fromCurrencyCode && fromCurrencyCode !== cfg.code) {
      const fromRate = EXCHANGE_RATES[fromCurrencyCode] ?? 1;
      const toRate   = EXCHANGE_RATES[cfg.code]          ?? 1;
      displayAmount  = amount * (toRate / fromRate);
    }
    try {
      return `${cfg.symbol}${Math.round(displayAmount).toLocaleString(cfg.locale)}`;
    } catch {
      return `${cfg.symbol}${Math.round(displayAmount).toLocaleString()}`;
    }
  };

  return (
    <LanguageContext.Provider value={{
      language,
      country,
      setLanguage,
      setCountry,
      t,
      formatCurrency,
      currencySymbol: getCurrencyCfg(country, language).symbol,
      currencyCode:   getCurrencyCfg(country, language).code,
    }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used within LanguageProvider');
  return ctx;
}

